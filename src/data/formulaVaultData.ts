interface CompactSpec {
  name: string;
  category: FormulaCategory;
  skillLevel: SkillLevel;
  difficulty: DifficultyTag;
  summary: string;
  syntaxArgs: SyntaxArg[];
  workplaceTip: string;
  headers: string[];
  rows: (string | number)[][];
  formulaCell: string;
  formulaText: string;
  outputValue: string;
  cells?: Record<string, CellData>;
  targetCell?: string;
}

function buildPresetFromSpec(spec: CompactSpec): SheetPreset {
  const cells: Record<string, CellData> = spec.cells ? { ...spec.cells } : {};

  if (!spec.cells) {
    const colLetters = ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H'];
    spec.headers.forEach((h, idx) => {
      cells[`${colLetters[idx]}1`] = { raw: h, format: 'header' };
    });
    spec.rows.forEach((row, rIdx) => {
      row.forEach((val, cIdx) => {
        const coord = `${colLetters[cIdx]}${rIdx + 2}`;
        const raw = String(val);
        cells[coord] = { raw };
      });
    });
    cells['E1'] = { raw: `${spec.name} Result`, format: 'header' };
    cells['E2'] = { raw: spec.formulaText };
  }

  const targetCell = spec.targetCell || (spec.cells ? spec.formulaCell : 'E2');

  return {
    id: `vault-${spec.name.toLowerCase()}`,
    title: `${spec.name} Interactive Sandbox`,
    skillLevel: spec.skillLevel,
    description: spec.summary,
    targetCell,
    cells,
    scenarioChips: [
      `How do I avoid common errors with ${spec.name}?`,
      `Explain each argument in ${spec.name}`,
      `Show a real FP&A workflow using ${spec.name}`,
    ],
    coachCard: {
      id: `cc-vault-${spec.name.toLowerCase()}`,
      title: `Mastering ${spec.name} in Production Sheets`,
      steps: [
        `Inspect the active formula inside cell ${targetCell}: ${spec.formulaText}`,
        'Edit any input value in columns A–C to watch the calculated output update immediately.',
        spec.workplaceTip,
      ],
      syntax: spec.formulaText,
      syntaxArgs: spec.syntaxArgs,
      pitfallWarning: spec.workplaceTip,
      nextStepChallenge: `Click an input cell and change a value, or tweak ${targetCell} in the fx bar to test edge cases.`,
      suggestedFormula: spec.formulaText,
      targetCell,
    },
  };
}

function makeFormula(spec: CompactSpec): FormulaDefinition {
  return {
    name: spec.name,
    category: spec.category,
    skillLevel: spec.skillLevel,
    difficulty: spec.difficulty,
    summary: spec.summary,
    syntaxPrefix: `=${spec.name}(`,
    syntaxArgs: spec.syntaxArgs,
    workplaceTip: spec.workplaceTip,
    preview: {
      headers: spec.headers,
      rows: spec.rows,
      formulaCell: spec.formulaCell,
      formulaText: spec.formulaText,
      outputValue: spec.outputValue,
    },
    preset: buildPresetFromSpec(spec),
  };
}

